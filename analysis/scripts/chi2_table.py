"""chi^2 per model and per band (radio by array, optical/UV, X-ray) -> output/tables/chi2.tex.

    python analysis/scripts/chi2_table.py [--floor 0.1] [--out output/tables/chi2.tex]

sigma^2 = err^2 + (floor x nuFnu)^2. Upper limits are excluded from the chi^2 but each one is checked against the
model (printed, and any violation is flagged in the table notes). Also writes analysis/runs/chi2.json with the
per-point values and the provenance of the inputs.
"""
import argparse
import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
from m87 import chi2, provenance  # noqa: E402
from m87.data import APERTURE_BY_NU, APERTURE_OF, load_obs  # noqa: E402
from m87.models import load_jet_model  # noqa: E402
from m87.paths import ROOT, RUNS, TABLES  # noqa: E402

MODELS = {"Jet-only": ("jet_only", None), "Jet+RIAF": ("jet_riaf", "riaf_m87")}
ARRAYS = ["EHT", "GMVA", "EAVN", "HSA", "EVN", "ALMA", "KVN", "VERA", "VLBA", "SMA"]
NAMES = {"HESS": "H.E.S.S."}


def fmt_ap(r):
    return r"3.5\times10^5" if r >= 1e4 else f"{r:g}"


def ap_label(a):
    """Aperture(s) of an array, in order of increasing frequency, e.g. "131/65 R_g"; "whole jet" if none."""
    aps = APERTURE_BY_NU[a].values() if a in APERTURE_BY_NU else [APERTURE_OF.get(a)]
    aps = list(dict.fromkeys(aps))  # unique, keep order
    return "whole jet" if aps == [None] else "$" + "/".join(fmt_ap(r) for r in aps) + r"\,R_{\rm g}$"


def groups():
    g = {}
    for a in ARRAYS:
        g[f"{a} ({ap_label(a)})"] = (lambda p, a=a: p.instrument == a)
    g["Radio, aperture-tagged"] = lambda p: p.band == "radio" and p.aperture is not None
    g["Radio, all"] = lambda p: p.band == "radio"
    g["_Radio, per-instrument apertures"] = lambda p: p.instrument in APERTURE_OF  # console only
    g["Optical/UV (HST, UVOT)"] = lambda p: p.band == "optuv"
    g["X-ray (Chandra, NuSTAR)"] = lambda p: p.band == "xray"
    g["Total"] = lambda p: p.band in ("radio", "optuv", "xray")
    return g


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--floor", type=float, default=0.1, help="systematic floor, fraction of nuFnu (default 0.1)")
    ap.add_argument("--out", type=Path, default=TABLES / "chi2.tex")
    args = ap.parse_args()
    obs = load_obs()
    res, pts_all, ul_bad = {}, {}, []
    for label, (run, riaf) in MODELS.items():
        pts = chi2.evaluate(load_jet_model(run, riaf), obs, args.floor)
        pts_all[label] = pts
        res[label] = chi2.summary(pts, groups())
        print(f"\n{label}: upper limits (model / limit)")
        for p in pts:
            if p.uplim:
                r = p.model / p.data
                flag = "  <-- VIOLATED" if r > 1 else ""
                print(f"  {p.instrument:8s} {p.nu:9.3e} Hz  {r:9.2e}{flag}")
                if r > 1:
                    ul_bad.append(f"{label}: {NAMES.get(p.instrument, p.instrument)} at {p.nu:.2e} Hz")

    # console table
    print(f"\nchi^2 (N points), floor = {args.floor:g}")
    print(f"{'band':34s}" + "".join(f"{m:>22s}" for m in MODELS))
    for g in groups():
        print(f"{g:34s}" + "".join(f"{res[m][g][1]:14.1f} ({res[m][g][0]:2d})" + " " * 3 for m in MODELS))

    # LaTeX table
    rows = []
    for g in groups():
        n = res["Jet-only"][g][0]
        if n == 0 or g.startswith("_"):
            continue
        cells = " & ".join(f"{res[m][g][1]:.1f}" for m in MODELS)
        if g == "Total":
            rows.append(r"\hline")
        label = "Radio, effective apertures" if g == "Radio, aperture-tagged" else g
        rows.append(f"{label} & {n} & {cells} \\\\")
        if g.startswith("SMA"):
            rows.append(r"\hline")
    tot = {m: res[m]["Total"] for m in MODELS}
    red = " & ".join(f"{tot[m][1] / tot[m][0]:.2f}" for m in MODELS)
    rows.append(rf"$\chi^2/N$ & & {red} \\")
    note = (f"Radio arrays are compared with the model (jet, counter-jet and RIAF) integrated within the effective aperture of radius $R_*$ given in parentheses, "
            f"$R_*$ = half the FWHM of the restoring beam of each observation (Table A1 of \\citealt{{EHTMWL2021}}); SMA, optical/UV and X-rays with the whole jet. "
            f"$\\sigma^2=\\sigma_{{\\rm obs}}^2+({args.floor:g}F)^2$. Upper limits and $\\gamma$-ray data are excluded; "
            + ("no upper limit is exceeded by either model." if not ul_bad else
               "upper limits exceeded: " + "; ".join(ul_bad) + "."))
    tex = "\n".join([
        "% generated by analysis/scripts/chi2_table.py -- do not edit by hand",
        r"\begin{table}",
        rf"\caption{{$\chi^2$ of the two models per band. {note}}}",
        r"\label{tab:chi2}",
        r"\centering",
        r"\begin{tabular}{lrrr}",
        r"\hline",
        r"Band / array & $N$ & Jet-only & Jet+RIAF \\",
        r"\hline",
        *rows,
        r"\hline",
        r"\end{tabular}",
        r"\end{table}", ""])
    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text(tex)
    print("\nwrote", args.out)

    js = RUNS / "chi2.json"
    provenance.write(js, script="analysis/scripts/chi2_table.py", floor=args.floor,
                     inputs={m: {r: json.load(open(RUNS / r / "provenance.json"))["date"]
                                 for r in filter(None, MODELS[m])} for m in MODELS},
                     summary={m: {g: {"N": n, "chi2": c} for g, (n, c) in res[m].items()} for m in MODELS},
                     points={m: [p.__dict__ for p in pts_all[m]] for m in MODELS},
                     upper_limits_violated=ul_bad)
    print("wrote", js.relative_to(ROOT))


if __name__ == "__main__":
    main()
